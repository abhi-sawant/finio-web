export type AccountType = 'checking' | 'savings' | 'cash' | 'credit' | 'investment' | 'wallet';
export type TransactionType = 'expense' | 'income' | 'transfer';
export type CategoryType = 'expense' | 'income' | 'both';
export type Theme = 'dark' | 'light' | 'system';
export type RecurrenceFrequency = 'daily' | 'weekly' | 'monthly' | 'yearly';
export type BudgetPeriod = 'weekly' | 'monthly' | 'yearly';

export interface Account {
  id: string;
  name: string;
  type: AccountType;
  color: string;
  icon: string;
  /** Cache of `openingBalance + Σ(transaction deltas)`. Recomputable — never the source of truth. */
  balance: number;
  /**
   * The balance before any recorded transaction. Immutable in normal use, which is what makes
   * `balance` derivable and any drift reconcilable.
   */
  openingBalance: number;
  createdAt: string;
  creditLimit?: number;
  /**
   * Day of the month (1–28) a credit account's statement closes. Absent means the lifecycle
   * fields below are unset and no due-date tracking applies to this account.
   */
  statementCloseDay?: number;
  /** Days after `statementCloseDay` that payment is due. Only meaningful alongside it. */
  paymentDueDays?: number;
  /** Minimum payment as a percent (0–100) of the outstanding balance at statement close. */
  minimumDuePercent?: number;
  /**
   * ISO timestamp of when the account was closed, or absent while it is open. Archiving keeps
   * every transaction — it only removes the account from pickers and running totals.
   */
  archivedAt?: string;
}

/** An account from a backup file or pre-v5 storage, where `openingBalance` may be absent. */
export type ImportedAccount = Omit<Account, 'openingBalance'> & { openingBalance?: number };

export interface Transaction {
  id: string;
  type: TransactionType;
  amount: number;
  accountId: string;
  toAccountId?: string;
  categoryId: string;
  date: string;
  note: string;
  labels: string[];
  createdAt: string;
  /** If this transaction was auto-generated by a recurring rule, the rule id. */
  recurringId?: string;
  /**
   * One receipt across multiple categories. Only meaningful for `type === 'expense'`; when
   * present, `categoryId` is `''` and every consumer must aggregate through
   * `transactionCategoryAmounts()` instead of reading `categoryId` directly. Always at least 2
   * entries (a single entry is just an unsplit category) summing exactly to `amount`.
   */
  splits?: TransactionSplit[];
}

export interface TransactionSplit {
  categoryId: string;
  amount: number;
}

export interface Category {
  id: string;
  name: string;
  icon: string;
  color: string;
  type: CategoryType;
}

export interface Label {
  id: string;
  name: string;
  color: string;
}

export interface Budget {
  id: string;
  /**
   * Empty string means "overall" budget across all expense categories. Ignored when
   * `labelId` is set.
   */
  categoryId: string;
  /** When set, the budget tracks every expense carrying this label instead of a category. */
  labelId?: string;
  /** Limit in INR, per `period`. */
  amount: number;
  /** How often the limit resets. Monthly periods follow `Settings.monthStartDay`. */
  period: BudgetPeriod;
  /**
   * Carry the previous period's unspent amount (or overspend, as a debt) into this one,
   * envelope-style, instead of starting every period back at `amount`.
   */
  rollover: boolean;
  createdAt: string;
}

export interface RecurringTransaction {
  id: string;
  type: TransactionType;
  amount: number;
  accountId: string;
  /** Destination account. Required for `transfer` rules, absent otherwise. */
  toAccountId?: string;
  categoryId: string;
  note: string;
  labels: string[];
  frequency: RecurrenceFrequency;
  /** ISO date of the first occurrence (also next due if never run). */
  startDate: string;
  /** ISO date after which the rule stops generating. Absent means it runs forever. */
  endDate?: string;
  /** Stop after this many occurrences in total. Absent means unlimited. */
  maxOccurrences?: number;
  /** Occurrences generated so far, counted against `maxOccurrences`. */
  occurrenceCount: number;
  /** ISO timestamp of when the rule was paused, or absent while it is active. */
  pausedAt?: string;
  /** ISO date of the most recent auto-generated occurrence, or null. */
  lastRunDate: string | null;
  createdAt: string;
}

export interface Settings {
  theme: Theme;
  userName: string;
  /** Whether to automatically download a local backup JSON once per day. */
  autoLocalBackup: boolean;
  /**
   * Day of the month a financial month begins (1–28). Anything other than 1 shifts every
   * "this month" total and monthly budget to a salary-cycle window.
   */
  monthStartDay: number;
  /**
   * ISO timestamp of when the first-run wizard was completed or skipped. Absent means this
   * is a fresh install and the wizard should run before anything else.
   */
  onboardedAt?: string;
  /** Mask every rendered amount behind dots, e.g. in public or over someone's shoulder. */
  hideAmounts: boolean;
}

export interface Goal {
  id: string;
  name: string;
  icon: string;
  color: string;
  targetAmount: number;
  /** ISO date. Absent means there's no deadline. */
  targetDate?: string;
  /**
   * Informational only — e.g. "this lives in my HDFC savings account". Progress is tracked
   * by `GoalContribution` entries, not by the account's balance or transactions.
   */
  linkedAccountId?: string;
  createdAt: string;
}

/** A manual log entry against a goal — the goal's own ledger, independent of transactions. */
export interface GoalContribution {
  id: string;
  goalId: string;
  /** Positive = contribution, negative = withdrawal. */
  amount: number;
  date: string;
  note: string;
  createdAt: string;
}

/** Someone you lend to or borrow from — a "who owes me / who I owe" ledger, per person. */
export interface Person {
  id: string;
  name: string;
  icon: string;
  color: string;
  createdAt: string;
}

/**
 * A manual ledger entry against a person — independent of accounts and transactions, like a
 * `GoalContribution`. Positive = they owe you more (you lent them money, or they owe you for
 * something). Negative = you owe them more (you borrowed, or you owe them). A settle-up adds a
 * balancing entry in the opposite direction and stamps `settledTransactionId` with the real
 * transaction it generated, since settling is the one moment actual money changes hands.
 */
export interface DebtEntry {
  id: string;
  personId: string;
  amount: number;
  date: string;
  note: string;
  settledTransactionId?: string;
  createdAt: string;
}

/** A saved shape for quickly re-adding a common transaction — everything but the date. */
export interface TransactionTemplate {
  id: string;
  name: string;
  type: TransactionType;
  amount: number;
  accountId: string;
  toAccountId?: string;
  categoryId: string;
  note: string;
  labels: string[];
  createdAt: string;
  /** Same rules as `Transaction.splits`. */
  splits?: TransactionSplit[];
}

/** Sanitized backup contents accepted by `importData`. */
export interface ImportPayload {
  accounts?: ImportedAccount[];
  transactions?: Transaction[];
  categories?: Category[];
  labels?: Label[];
  budgets?: Budget[];
  recurring?: RecurringTransaction[];
  templates?: TransactionTemplate[];
  goals?: Goal[];
  goalContributions?: GoalContribution[];
  people?: Person[];
  debtEntries?: DebtEntry[];
  settings?: Settings;
}

export type ImportMode = 'replace' | 'merge';

export interface FinanceStore {
  accounts: Account[];
  transactions: Transaction[];
  categories: Category[];
  labels: Label[];
  budgets: Budget[];
  recurring: RecurringTransaction[];
  templates: TransactionTemplate[];
  goals: Goal[];
  goalContributions: GoalContribution[];
  people: Person[];
  debtEntries: DebtEntry[];
  settings: Settings;
  isHydrated: boolean;
  /** ISO date (YYYY-MM-DD) of the last automatic local backup download, or null. */
  lastLocalBackupAt: string | null;
  setLastLocalBackupAt: (date: string) => void;

  addAccount: (account: Omit<Account, 'id' | 'createdAt' | 'openingBalance'>) => void;
  updateAccount: (id: string, updates: Partial<Omit<Account, 'id'>>) => void;
  /**
   * Close or reopen an account. Unlike `deleteAccount` this is non-destructive: transactions,
   * balances and recurring rules survive, so it is the right default for a closed bank account.
   */
  setAccountArchived: (id: string, archived: boolean) => void;
  deleteAccount: (id: string) => void;
  /**
   * Rebuild every account balance from its opening balance plus its transactions.
   * Returns how many accounts moved and the net drift that was corrected.
   */
  recomputeBalances: () => { changed: number; totalDrift: number };

  addTransaction: (transaction: Omit<Transaction, 'id' | 'createdAt'>) => string;
  updateTransaction: (id: string, updates: Partial<Omit<Transaction, 'id'>>) => void;
  /** Removes the transaction and reverses its delta. Returns the removed row so callers can undo. */
  deleteTransaction: (id: string) => Transaction | null;
  /**
   * Re-insert a previously deleted transaction verbatim — same id, same delta. Undoing a
   * delete must not mint a new id, or the row would diverge from any backup that has it.
   */
  restoreTransaction: (transaction: Transaction) => void;
  /** Removes every listed transaction and reverses their deltas. Returns the removed rows for undo. */
  bulkDeleteTransactions: (ids: string[]) => Transaction[];
  /** Re-insert previously deleted transactions verbatim. Same double-undo guard as `restoreTransaction`. */
  restoreTransactions: (transactions: Transaction[]) => void;
  /** Reassign every listed transaction to a single category. */
  bulkRecategorize: (ids: string[], categoryId: string) => void;
  /** Add a label to every listed transaction that doesn't already carry it. */
  bulkAddLabel: (ids: string[], labelId: string) => void;

  /** Save a transaction's shape (everything but date) as a reusable template. */
  addTemplate: (template: Omit<TransactionTemplate, 'id' | 'createdAt'>) => string;
  deleteTemplate: (id: string) => void;

  addGoal: (goal: Omit<Goal, 'id' | 'createdAt'>) => string;
  updateGoal: (id: string, updates: Partial<Omit<Goal, 'id'>>) => void;
  /** Removes the goal and every contribution logged against it. */
  deleteGoal: (id: string) => void;

  addContribution: (contribution: Omit<GoalContribution, 'id' | 'createdAt'>) => string;
  /** Removes the contribution. Returns the removed row so callers can undo. */
  deleteContribution: (id: string) => GoalContribution | null;
  /** Re-insert a previously deleted contribution verbatim — same id, no double-undo. */
  restoreContribution: (contribution: GoalContribution) => void;

  addPerson: (person: Omit<Person, 'id' | 'createdAt'>) => string;
  updatePerson: (id: string, updates: Partial<Omit<Person, 'id'>>) => void;
  /** Removes the person and every debt entry logged against them. */
  deletePerson: (id: string) => void;

  addDebtEntry: (entry: Omit<DebtEntry, 'id' | 'createdAt'>) => string;
  /** Removes the entry. Returns the removed row so callers can undo. */
  deleteDebtEntry: (id: string) => DebtEntry | null;
  /** Re-insert a previously deleted entry verbatim — same id, no double-undo. */
  restoreDebtEntry: (entry: DebtEntry) => void;

  addCategory: (category: Omit<Category, 'id'>) => void;
  updateCategory: (id: string, updates: Partial<Omit<Category, 'id'>>) => void;
  deleteCategory: (id: string) => void;

  addLabel: (label: Omit<Label, 'id'>) => void;
  updateLabel: (id: string, updates: Partial<Omit<Label, 'id'>>) => void;
  deleteLabel: (id: string) => void;

  /** Adding a budget for a scope that already has one replaces it — one limit per scope. */
  addBudget: (budget: Omit<Budget, 'id' | 'createdAt'>) => void;
  updateBudget: (id: string, updates: Partial<Omit<Budget, 'id'>>) => void;
  deleteBudget: (id: string) => void;

  /**
   * Create a recurring rule. Pass `lastRunDate` to start the schedule mid-stream — that is how
   * "skip the backfill" is expressed: the rule stays aligned to its `startDate` cadence but
   * generates nothing for occurrences on or before that date.
   */
  addRecurring: (
    rule: Omit<RecurringTransaction, 'id' | 'createdAt' | 'occurrenceCount' | 'lastRunDate'> & {
      lastRunDate?: string | null;
    },
  ) => string;
  updateRecurring: (id: string, updates: Partial<Omit<RecurringTransaction, 'id'>>) => void;
  /** Pause or resume a rule without losing its schedule or history. */
  setRecurringPaused: (id: string, paused: boolean) => void;
  deleteRecurring: (id: string) => void;
  /** Generate any due transactions from recurring rules. Returns count generated. */
  processRecurring: () => number;

  updateSettings: (updates: Partial<Settings>) => void;

  resetToDefaults: () => void;
  /**
   * Apply an (already validated) backup payload. `replace` swaps each provided collection,
   * `merge` unions rows by id with incoming winning. Balances are recomputed either way.
   */
  importData: (data: ImportPayload, options?: { mode?: ImportMode }) => void;

  setHydrated: (hydrated: boolean) => void;
}
